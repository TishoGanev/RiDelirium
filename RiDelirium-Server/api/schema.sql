-- RideTogether API. MySQL 8 / MariaDB 10.5+, utf8mb4.
--
-- Data kept per rider: a random id, a hash of their access token, a display name and initials
-- (both chosen by the rider), a "riding until" time, the last day they used the app and, only while
-- they are riding, their latest position (lat/lon) and speed, which are overwritten on every update, shown
-- only to their friends and cleared ten minutes after the last update (or at once when they stop sharing). No history, email, phone, device info, IP address
-- or ride data is stored.

USE RideTogether;

CREATE TABLE riders (
    id           CHAR(36)     NOT NULL PRIMARY KEY,   -- generated by the app, never reused
    token_hash   CHAR(64)     NOT NULL UNIQUE,        -- sha256 of the access token; the token itself is not stored
    name         VARCHAR(30)  NOT NULL,
    initials     VARCHAR(2)   NOT NULL,
    sport        ENUM('ski','board','bike') NOT NULL DEFAULT 'board',  -- what they ride; shown on their map tag
    riding_until DATETIME     NULL,                   -- UTC; set by the app's heartbeat, expires by itself
    lat          DECIMAL(8,5) NULL,                   -- latest position while riding; NULL otherwise
    lon          DECIMAL(8,5) NULL,
    speed        DECIMAL(4,1) NULL,                   -- km/h at that position
    seen_at      DATETIME     NULL,                   -- UTC; when that position was sent ("last seen")
    last_seen    DATE         NOT NULL,               -- UTC; only used to purge inactive riders
    KEY (riding_until)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- A crew: a group of riders who see each other on the map. Anyone with its code can join.
CREATE TABLE crews (
    id         CHAR(16)    NOT NULL PRIMARY KEY,        -- random hex
    name       VARCHAR(30) NOT NULL,
    code       CHAR(8)     NOT NULL UNIQUE,             -- what the QR code and invite link carry
    owner_id   CHAR(36)    NOT NULL,                    -- passes to the oldest member when the owner leaves
    created_at DATETIME    NOT NULL                     -- UTC
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Who is in which crew, and until when. NULL expires_at means "until I leave". Riders see each other only while
-- they share at least one crew where neither membership has expired.
CREATE TABLE crew_members (
    crew_id    CHAR(16) NOT NULL,
    rider_id   CHAR(36) NOT NULL,
    joined_at  DATETIME NOT NULL,                       -- UTC
    expires_at DATETIME NULL,                           -- UTC
    PRIMARY KEY (crew_id, rider_id),
    KEY (rider_id),
    KEY (expires_at),
    FOREIGN KEY (crew_id) REFERENCES crews (id) ON DELETE CASCADE,
    FOREIGN KEY (rider_id) REFERENCES riders (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Where to send "a friend joined / left your crew". One row per phone; the token is Apple's or Google's
-- address for the app on that phone and means nothing elsewhere. Removed with the rider.
CREATE TABLE devices (
    token    VARCHAR(255) NOT NULL PRIMARY KEY,
    rider_id CHAR(36)     NOT NULL,
    platform ENUM('ios','android') NOT NULL,
    sandbox  TINYINT(1)   NOT NULL DEFAULT 0,        -- iOS development build (APNs sandbox)
    KEY (rider_id),
    FOREIGN KEY (rider_id) REFERENCES riders (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- "Wait for me": one row per request, so the friend's phone can ask what is pending, answer it, and the
-- sender can learn whether it was answered. No positions are stored, only the distance the sender gave.
-- Rows are purged after a day.
CREATE TABLE waits (
    id          CHAR(16)     NOT NULL PRIMARY KEY,   -- random hex
    from_rider  CHAR(36)     NOT NULL,
    to_rider    CHAR(36)     NOT NULL,
    distance_m  INT          NULL,
    created_at  DATETIME     NOT NULL,               -- UTC
    accepted_at DATETIME     NULL,                   -- UTC; set when the friend taps "OK, waiting"
    KEY (to_rider, created_at),
    KEY (from_rider, created_at),
    FOREIGN KEY (from_rider) REFERENCES riders (id) ON DELETE CASCADE,
    FOREIGN KEY (to_rider) REFERENCES riders (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Where to push updates for a rider's Live Activity (iOS lock screen / Dynamic Island). The token belongs to
-- one running activity and changes with every ride; it is removed when the ride ends.
CREATE TABLE live_activities (
    rider_id   CHAR(36)     NOT NULL PRIMARY KEY,
    token      VARCHAR(255) NOT NULL,
    sandbox    TINYINT(1)   NOT NULL DEFAULT 0,
    updated_at DATETIME     NOT NULL,
    FOREIGN KEY (rider_id) REFERENCES riders (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- People a rider has been in a crew with, kept 30 days after they last rode together so "recent riders" can be
-- invited again. One row per pair; rider_a < rider_b. Holds no positions or ride data.
CREATE TABLE ridden_with (
    rider_a CHAR(36) NOT NULL,
    rider_b CHAR(36) NOT NULL,
    last_at DATETIME NOT NULL,                       -- UTC; when they were last in a crew together
    PRIMARY KEY (rider_a, rider_b),
    KEY (rider_b),
    FOREIGN KEY (rider_a) REFERENCES riders (id) ON DELETE CASCADE,
    FOREIGN KEY (rider_b) REFERENCES riders (id) ON DELETE CASCADE,
    CHECK (rider_a < rider_b)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Abuse limiting. The key is a salted hash, never a raw IP; rows are purged after a day.
CREATE TABLE rate_limits (
    k      CHAR(64) NOT NULL,
    bucket INT      NOT NULL,
    n      INT      NOT NULL DEFAULT 1,
    PRIMARY KEY (k, bucket)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
